import { component, check, assert } from "../component.mjs"

await component("resizable", async (page) => {
  await check("arrow keys on a handle move it", async () => {
    const handle = page.locator("ui-resizable-handle").first()
    const before = Number(await handle.getAttribute("aria-valuenow"))
    await handle.focus()
    await page.keyboard.press("ArrowRight")
    await page.keyboard.press("ArrowRight")
    await page.waitForTimeout(150)
    const after = Number(await handle.getAttribute("aria-valuenow"))
    assert(after > before, `${before} → ${after}`)
  })
  await check("dragging resizes", async () => {
    const one = page.locator("ui-resizable-panel#one")
    const width = (await one.boundingBox()).width
    const handle = await page.locator("ui-resizable-handle").first().boundingBox()
    await page.mouse.move(handle.x + handle.width / 2, handle.y + handle.height / 2)
    await page.mouse.down()
    await page.mouse.move(handle.x - 80, handle.y + handle.height / 2, { steps: 5 })
    await page.mouse.up()
    assert((await one.boundingBox()).width < width - 40, "didn't shrink")
  })
  await check("a grip appears where the pointer meets the handle, and widens while dragging", async () => {
    const handle = page.locator("#sidebar-layout > ui-resizable-handle")
    const box = await handle.boundingBox()
    await page.mouse.move(box.x - 30, box.y + 40)
    await page.mouse.move(box.x + box.width / 2, box.y + 40, { steps: 3 })
    await page.waitForTimeout(250)
    const pill = handle.locator("[data-slot=resizable-pill]")
    let grip = await pill.boundingBox()
    const opacity = await pill.evaluate((element) => getComputedStyle(element).opacity)
    assert(opacity === "1" && Math.abs(grip.y + grip.height / 2 - (box.y + 40)) < 2, `grip at ${grip.y + grip.height / 2} for ${box.y + 40}, opacity ${opacity}`)
    await page.mouse.down()
    await page.mouse.move(box.x + 20, box.y + 60, { steps: 3 })
    await page.waitForTimeout(200)
    grip = await pill.boundingBox()
    await page.mouse.up()
    assert(grip.width > 5 && Math.abs(grip.y + grip.height / 2 - (box.y + 60)) < 2, `dragging grip ${JSON.stringify(grip)}`)
  })
  await check("a collapsible panel folds with Enter on its handle, and comes back", async () => {
    const handle = page.locator("#sidebar-layout > ui-resizable-handle")
    await handle.focus()
    await page.keyboard.press("Enter")
    await page.waitForTimeout(100)
    assert(await page.locator("#sidebar").getAttribute("data-collapsed") !== null, "didn't collapse")
    await page.keyboard.press("Enter")
    await page.waitForTimeout(100)
    assert(await page.locator("#sidebar").getAttribute("data-collapsed") === null, "didn't come back")
  })
})
