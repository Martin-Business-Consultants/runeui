import { component, check, assert } from "../component.mjs"

await component("menu", async (page) => {
  const highlighted = () => page.evaluate(() => document.querySelector("#account-menu > ui-menu-content[data-open] [data-highlighted]")?.textContent.trim())

  await check("opens from the keyboard and arrows move through its items", async () => {
    await page.focus("#account-menu ui-menu-trigger button")
    await page.keyboard.press("ArrowDown")
    await page.waitForSelector("#account-menu [data-slot=menu-content][data-open]")
    await page.waitForTimeout(150)
    const first = await highlighted()
    await page.keyboard.press("ArrowDown")
    const second = await highlighted()
    assert(first && second && first !== second, `highlight ${first} → ${second}`)
  })
  await check("a submenu opens toward its arrow and Escape closes just it", async () => {
    await page.hover("#account-menu ui-menu-sub-trigger")
    await page.waitForSelector("#account-menu ui-menu-sub-content[data-open]", { timeout: 3000 })
    await page.keyboard.press("ArrowRight")
    await page.keyboard.press("Escape")
    await page.waitForSelector("#account-menu ui-menu-sub-content[data-open]", { state: "detached" })
    assert(await page.$("#account-menu > ui-menu-content[data-open]"), "the whole menu closed")
    await page.keyboard.press("Escape")
  })
  await check("choosing an action fires action with its value and closes the menu", async () => {
    await page.evaluate(() => { window.chosen = null; document.querySelector("#account-menu").addEventListener("action", (e) => { window.chosen = e.detail.value }, { once: true }) })
    await page.click("#account-menu ui-menu-trigger button")
    await page.click("#account-menu ui-menu-item[value=new-team]")
    await page.waitForFunction(() => window.chosen === "new-team")
    await page.waitForSelector("#account-menu [data-slot=menu-content][data-open]", { state: "detached" })
  })
  await check("a link item is a real link", async () => {
    assert(await page.getAttribute("#account-menu a[href='#profile']", "role") === "menuitem", "link isn't a menuitem")
  })
  await check("a disabled item can't be chosen; a destructive one is marked", async () => {
    assert(await page.getAttribute("#account-menu ui-menu-item[value=api]", "aria-disabled") === "true", "API not disabled")
    assert(await page.getAttribute("#account-menu ui-menu-item[value=logout]", "data-variant") === "destructive", "logout not destructive")
  })
  await check("check and radio items toggle and stay open", async () => {
    await page.click("#view-menu ui-menu-trigger button")
    await page.click("#view-menu ui-menu-checkbox-item[value=activity-bar]")
    assert(await page.getAttribute("#view-menu ui-menu-checkbox-item[value=activity-bar]", "aria-checked") === "true", "checkbox didn't check")
    await page.click("#view-menu ui-menu-radio-item[value=top]")
    assert(await page.getAttribute("#view-menu ui-menu-radio-item[value=top]", "aria-checked") === "true", "radio didn't move")
    assert(await page.getAttribute("#view-menu ui-menu-radio-item[value=bottom]", "aria-checked") === "false", "old radio still on")
    assert(await page.$("#view-menu [data-slot=menu-content][data-open]"), "menu closed")
    await page.keyboard.press("Escape")
  })
  await check("a context menu opens on right-click", async () => {
    await page.click(".ui-context-area", { button: "right" })
    await page.waitForSelector("#context-menu [data-slot=menu-content][data-open]", { timeout: 3000 })
    await page.keyboard.press("Escape")
  })
  await check("one menu for many buttons: it opens beside the button pressed, which gets focus back", async () => {
    const near = async (id) => page.evaluate((id) => { const b = document.getElementById(id).getBoundingClientRect(), m = document.querySelector("#row-menu [data-slot=menu-content]").getBoundingClientRect(); return Math.abs(m.left - b.left) < 40 && m.top >= b.bottom - 2 && m.top - b.bottom < 20 }, id)
    await page.evaluate(() => { window.opened = []; document.getElementById("row-menu").addEventListener("runeui:open", (event) => window.opened.push(event.detail.opener.id)) })
    await page.click("#row-b-actions")
    await page.waitForSelector("#row-menu [data-slot=menu-content][data-open]", { timeout: 3000 })
    assert(await near("row-b-actions"), "not beside row B's button")
    assert(await page.getAttribute("#row-b-actions", "aria-expanded") === "true", "no aria-expanded")
    assert(await page.evaluate(() => document.getElementById("row-menu").runeuiOpener.id) === "row-b-actions", "runeuiOpener")
    await page.keyboard.press("Escape")
    await page.waitForFunction(() => !document.querySelector("#row-menu [data-slot=menu-content][data-open]"))
    assert(await page.getAttribute("#row-b-actions", "aria-expanded") === "false", "aria-expanded stayed")
    assert(await page.evaluate(() => document.activeElement.id) === "row-b-actions", "focus didn't return")
    await page.click("#row-a-actions")
    await page.waitForSelector("#row-menu [data-slot=menu-content][data-open]", { timeout: 3000 })
    assert(await near("row-a-actions"), "not beside row A's button")
    assert((await page.evaluate(() => window.opened)).join() === "row-b-actions,row-a-actions", "runeui:open")
    const chosen = page.evaluate(() => new Promise((resolve) => document.getElementById("row-menu").addEventListener("action", (event) => resolve(event.detail.value), { once: true })))
    await page.click("#row-menu ui-menu-item[value=archive]")
    assert(await chosen === "archive", "no action")
  })
  await check("pressing the button again closes it", async () => {
    await page.click("#row-a-actions")
    await page.waitForSelector("#row-menu [data-slot=menu-content][data-open]", { timeout: 3000 })
    await page.click("#row-a-actions")
    await page.waitForTimeout(400)
    assert(!(await page.$("#row-menu [data-slot=menu-content][data-open]")), "still open")
  })
  await check("an item with data-runeui-open opens its dialog, chosen with the keys or the pointer", async () => {
    const open = () => page.evaluate(() => document.getElementById("menu-shortcuts").api?.isOpen?.() === true)
    await page.focus("#help-menu ui-menu-trigger button")
    await page.keyboard.press("Enter")
    await page.waitForSelector("#help-menu [data-slot=menu-content][data-open]", { timeout: 3000 })
    await page.waitForFunction(() => document.activeElement?.closest?.("ui-menu-item[value=shortcuts]"), null, { timeout: 3000 })
    await page.keyboard.press("Enter")
    await page.waitForFunction(() => document.getElementById("menu-shortcuts").api?.isOpen?.() === true, null, { timeout: 3000 })
    await page.keyboard.press("Escape")
    await page.waitForFunction(() => document.getElementById("menu-shortcuts").api?.isOpen?.() === false, null, { timeout: 3000 })
    await page.click("#help-menu ui-menu-trigger button")
    await page.click("#help-menu ui-menu-item[value=shortcuts]")
    await page.waitForFunction(() => document.getElementById("menu-shortcuts").api?.isOpen?.() === true, null, { timeout: 3000 })
    assert(await open(), "not open")
    await page.keyboard.press("Escape")
  })
  await check("an item with data-runeui-theme switches light and dark once, chosen with the keys or the pointer", async () => {
    const dark = () => page.evaluate(() => document.documentElement.classList.contains("dark"))
    const before = await dark()
    await page.focus("#help-menu ui-menu-trigger button")
    await page.keyboard.press("Enter")
    await page.waitForSelector("#help-menu [data-slot=menu-content][data-open]", { timeout: 3000 })
    await page.keyboard.press("ArrowDown")
    await page.waitForFunction(() => document.activeElement?.closest?.("ui-menu-item[value=theme]"), null, { timeout: 3000 })
    await page.keyboard.press("Enter")
    await page.waitForFunction((was) => document.documentElement.classList.contains("dark") !== was, before, { timeout: 3000 })
    assert(await page.evaluate(() => document.documentElement.dataset.theme) === (before ? "light" : "dark"), "data-theme didn't follow")
    await page.click("#help-menu ui-menu-trigger button")
    await page.click("#help-menu ui-menu-item[value=theme]")
    await page.waitForTimeout(300)
    assert(await dark() === before, "the pointer toggled twice, or not at all")
    await page.evaluate(() => localStorage.removeItem("runeui-theme"))
  })
})
