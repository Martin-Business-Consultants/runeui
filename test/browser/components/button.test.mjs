import { component, check, assert } from "../component.mjs"

await component("button", async (page) => {
  await check("a link button is an <a>, a disabled one can't be pressed", async () => {
    assert(await page.locator("a.ui-button:not([data-variant=link])").count() === 1, "no link button")
    assert(await page.locator("button.ui-button:disabled").count() === 1, "no disabled button")
  })
  await check("an icon-only button has a name", async () => {
    assert(await page.getByRole("button", { name: "Next" }).count() === 1, "icon button isn't named")
  })
  await check("data-turbo-confirm asks, then submits", async () => {
    await page.click("text=Delete project")
    await page.waitForSelector("#runeui-confirm [data-slot=alert-dialog-content]:not([hidden])")
    assert((await page.locator("#runeui-confirm ui-alert-dialog-description").innerText()).includes("can't be undone"), "no description")
    await page.click("#runeui-confirm [data-confirm-accept]")
    await page.waitForSelector("[data-slot=toast] >> text=Received", { timeout: 4000 })
  })
  await check("pressed, a button gives a little; not under reduced motion", async () => {
    const button = page.locator(".ui-button", { hasText: "Secondary" })
    await button.hover()
    await page.mouse.down()
    await page.waitForTimeout(250)
    const pressed = await button.evaluate((element) => getComputedStyle(element).transform)
    await page.mouse.up()
    assert(pressed.startsWith("matrix(0.97"), `pressed transform is ${pressed}`)
    await page.emulateMedia({ reducedMotion: "reduce" })
    await button.hover()
    await page.mouse.down()
    await page.waitForTimeout(100)
    const still = await button.evaluate((element) => getComputedStyle(element).transform)
    await page.mouse.up()
    await page.emulateMedia({ reducedMotion: "no-preference" })
    assert(still === "none", `reduced motion transform is ${still}`)
  })
  await check("swap: one name, the width kept, the next label on hover and at once on focus", async () => {
    const button = page.getByRole("button", { name: "Download for macOS, 42 MB" })
    assert(await button.count() === 1, "swap button isn't named by its aria-label")
    assert(await page.getByRole("button", { name: "Follow, Get updates" }).count() === 1, "default name isn't both labels")
    const width = (await button.boundingBox()).width
    const next = button.locator("[data-slot=button-swap-next]")
    assert(await next.evaluate((element) => getComputedStyle(element).opacity) === "0", "next label shows at rest")
    await button.hover()
    await page.waitForTimeout(350)
    assert(await next.evaluate((element) => getComputedStyle(element).opacity) === "1", "hover didn't swap")
    assert(Math.abs((await button.boundingBox()).width - width) < 0.5, "the width changed")
    await page.mouse.move(0, 0)
    await page.waitForTimeout(350)
    // A key press first, so focus() counts as keyboard focus (focus-visible).
    await page.keyboard.press("Shift")
    await button.focus()
    const opacity = await next.evaluate((element) => getComputedStyle(element).opacity)
    assert(opacity === "1", `focus didn't show the next label at once (${opacity})`)
  })
  await check("swap under reduced motion crossfades without moving", async () => {
    await page.evaluate(() => document.activeElement?.blur())
    await page.emulateMedia({ reducedMotion: "reduce" })
    const next = page.getByRole("button", { name: "Download for macOS, 42 MB" }).locator("[data-slot=button-swap-next]")
    const style = await next.evaluate((element) => { const s = getComputedStyle(element); return { transform: s.transform, property: s.transitionProperty, duration: s.transitionDuration } })
    await page.emulateMedia({ reducedMotion: "no-preference" })
    assert(style.transform === "none" && style.property === "opacity" && style.duration === "0.15s", JSON.stringify(style))
  })
  await check("a link's underline is plucked where the mouse comes in, and rings out", async () => {
    const link = page.locator("a.ui-button[data-variant=link]", { hasText: "Get in touch" })
    await page.waitForFunction(() => document.querySelector("a.ui-button[data-variant=link][data-pluck]"))
    const box = await link.boundingBox()
    await page.mouse.move(box.x - 20, box.y + box.height / 2)
    await page.mouse.move(box.x + box.width * 0.3, box.y + box.height / 2, { steps: 4 })
    await page.waitForTimeout(50)
    assert(await link.getAttribute("data-plucked") === "" && await link.getAttribute("data-ringing") === "", "not plucked")
    const d = await link.locator("path").getAttribute("d")
    assert(!d.startsWith("M0 6 Q50 "), `the bend isn't where the pointer came in (${d})`)
    const duration = await link.evaluate((element) => element.style.getPropertyValue("--ui-pluck-duration"))
    assert(/^\d+ms$/.test(duration), `no duration from its width (${duration})`)
    await page.mouse.move(0, 0)
    await page.waitForTimeout(1500)
    assert(await link.getAttribute("data-plucked") === null && await link.getAttribute("data-ringing") === null, "still plucked after leaving")
  })
  await check("keyboard focus shows a link's underline flat, at once", async () => {
    const link = page.locator("a.ui-button[data-variant=link]", { hasText: "Bio" })
    await page.keyboard.press("Shift")
    await link.focus()
    const clip = await link.locator("[data-slot=button-string]").evaluate((element) => getComputedStyle(element).clipPath)
    assert(clip.includes("-1px"), `the underline isn't open on focus (${clip})`)
  })
})
